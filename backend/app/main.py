import os
from pydantic import BaseModel, Field
from fastapi import HTTPException
import httpx
import time
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

app = FastAPI(
    title="NeuralForge AI",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173"],
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)


@app.get("/health")
def health():
    return {
        "status": "ok",
        "service": "NeuralForge AI",
        "model_loaded": False
    }


class ChatRequest(BaseModel):
    message: str = Field(min_length=1, max_length=4000)


@app.post("/chat")
async def chat(request: ChatRequest):
    start = time.perf_counter()
    mode = os.getenv("NEURALFORGE_MODE", "mock").lower()

    if mode == "mock":
        response = (
            "DEMO MODE — This is a simulated response, "
            "not generated by the trained model.\n\n"
            "1. Identify the exact error and affected systems.\n"
            "2. Check connectivity, permissions, and relevant logs.\n"
            "3. Review recent configuration changes.\n"
            "4. Apply approved fixes and verify the result.\n"
            "5. Escalate with diagnostic evidence if unresolved."
        )
        model_name = "mock-demo"

    elif mode == "remote":
        url = os.getenv("NEURALFORGE_API_URL", "").rstrip("/")
        api_key = os.getenv("NEURALFORGE_API_KEY", "")

        if not url or not api_key:
            raise HTTPException(
                status_code=503,
                detail="Remote inference is not configured",
            )

        try:
            async with httpx.AsyncClient(timeout=120) as client:
                result = await client.post(
                    f"{url}/generate",
                    json={"message": request.message},
                    headers={"x-api-key": api_key},
                )
                result.raise_for_status()
                data = result.json()

            response = data["response"]
            model_name = data.get("model", "NeuralForge QLoRA")

        except (httpx.HTTPError, ValueError, KeyError):
            raise HTTPException(
                status_code=502,
                detail="Inference service unavailable",
            )

    else:
        raise HTTPException(
            status_code=500,
            detail="Invalid inference mode",
        )

    return {
        "response": response,
        "model": model_name,
        "mode": mode,
        "latency_ms": round(
            (time.perf_counter() - start) * 1000, 2
        ),
    }
